type capturedWorkspaceFile struct {
	Path   string `json:"path"`
	Size   int64  `json:"size"`
	Mode   uint32 `json:"mode"`
	SHA256 string `json:"sha256"`
}
type capturedWorkspaceManifest struct {
	SchemaVersion int                     `json:"schemaVersion"`
	Files         []capturedWorkspaceFile `json:"files"`
}

func reconstructWorkspace(captureRoot, destination string) (retErr error) {
	manifestBytes, err := evalfs.Read(captureRoot, "final-workspace.json")
	if err != nil {
		return err
	}
	var manifest capturedWorkspaceManifest
	decoder := json.NewDecoder(bytes.NewReader(manifestBytes))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&manifest); err != nil || manifest.SchemaVersion != 1 {
		return errors.New("invalid final workspace manifest")
	}
	archive, err := evalfs.Read(captureRoot, "final-workspace.tar.gz")
	if err != nil {
		return err
	}
	gz, err := gzip.NewReader(bytes.NewReader(archive))
	if err != nil {
		return err
	}
	defer func() { retErr = errors.Join(retErr, gz.Close()) }()
	files := make(map[string][]byte, len(manifest.Files))
	modes := make(map[string]os.FileMode, len(manifest.Files))
	reader := tar.NewReader(io.LimitReader(gz, 16<<20))
	for {
		header, nextErr := reader.Next()
		if nextErr == io.EOF {
			break
		}
		if nextErr != nil {
			return nextErr
		}
		if header.Typeflag != tar.TypeReg || !filepath.IsLocal(filepath.FromSlash(header.Name)) || header.Size < 0 || header.Size > evalfs.MaxFileBytes || header.Mode < 0 || header.Mode > 0o777 {
			return errors.New("unsafe final workspace archive entry")
		}
		name := filepath.ToSlash(filepath.Clean(filepath.FromSlash(header.Name)))
		if _, exists := files[name]; exists {
			return errors.New("duplicate final workspace archive entry")
		}
		data, readErr := io.ReadAll(io.LimitReader(reader, evalfs.MaxFileBytes+1))
		if readErr != nil || int64(len(data)) != header.Size {
			return errors.New("invalid final workspace archive payload")
		}
		files[name], modes[name] = data, os.FileMode(uint32(header.Mode))
	}
	if len(files) != len(manifest.Files) || len(files) > 2048 {
		return errors.New("final workspace manifest/archive mismatch")
	}
	previous := ""
	for _, item := range manifest.Files {
		data, ok := files[item.Path]
		sum := sha256.Sum256(data)
		if !ok || item.Path <= previous || item.Size != int64(len(data)) || item.Mode != uint32(modes[item.Path]) || item.SHA256 != hex.EncodeToString(sum[:]) {
			return errors.New("final workspace manifest verification failed")
		}
		previous = item.Path
	}
	if err := os.Mkdir(destination, 0o700); err != nil {
		return err
	}
	for _, item := range manifest.Files {
		if err := evalfs.WriteExclusive(destination, item.Path, files[item.Path]); err != nil {
			return err
		}
		if err := evalfs.Chmod(destination, item.Path, os.FileMode(item.Mode)); err != nil {
			return err
		}
	}
	return nil
}

func validRunID(value string) bool {
	if len(value) < 1 || len(value) > 128 {
		return false
	}
	for _, r := range value {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '-', r == '_', r == '.':
		default:
			return false
		}
	}
	return true
}

func normalizeSnapshotModes(root string) error {
	files, err := evalfs.Files(root)
	if err != nil {
		return err
	}
	for _, rel := range files {
		if err := evalfs.Chmod(root, rel, 0o600); err != nil {
			return err
		}
	}
	return nil
}

func copyTree(src, dst string) error {
	files, err := evalfs.Files(src)
	if err != nil {
		return err
	}
	for _, rel := range files {
		data, err := evalfs.Read(src, rel)
		if err != nil {
			return err
		}
		if err := evalfs.WriteExclusive(dst, rel, data); err != nil {
			return err
		}
	}
	return nil
}

func snapshotTree(root string) (map[string]fileState, error) {
	files, err := evalfs.Files(root)
	if err != nil {
		return nil, err
	}
	out := make(map[string]fileState, len(files))
	for _, rel := range files {
		data, err := evalfs.Read(root, rel)
		if err != nil {
			return nil, err
		}
		path, err := evalfs.Path(root, rel)
		if err != nil {
			return nil, err
		}
		info, err := os.Stat(path)
		if err != nil {
			return nil, err
		}
		sum := sha256.Sum256(data)
		out[rel] = fileState{Hash: hex.EncodeToString(sum[:]), Mode: uint32(info.Mode().Perm())}
	}
	return out, nil
}
func commonParity(base, treated map[string]fileState) bool {
	for name, state := range base {
		if treated[name] != state {
			return false
		}
	}
	for name := range treated {
		if _, ok := base[name]; !ok && name != "llms.txt" && name != "trails.json" {
			return false
		}
	}
	return true
}

func parseControl(raw []byte, attempt string) ([]controlFrame, error) {
	if len(raw) > maxControlBytes {
		return nil, errors.New("control protocol exceeds byte limit")
	}
	scanner := bufio.NewScanner(bytes.NewReader(raw))
	scanner.Buffer(make([]byte, 1024), maxControlBytes)
	frames := make([]controlFrame, 0, 2)
	for scanner.Scan() {
		if len(frames) == maxControlFrames || len(scanner.Bytes()) == 0 {
			return frames, errors.New("invalid control frame count")
		}
		var f controlFrame
		dec := json.NewDecoder(bytes.NewReader(scanner.Bytes()))
		dec.DisallowUnknownFields()
		if err := dec.Decode(&f); err != nil {
			return frames, err
		}
		var trailing any
		if err := dec.Decode(&trailing); !errors.Is(err, io.EOF) {
			return frames, errors.New("trailing JSON in control frame")
		}
		if f.AttemptID != attempt {
			return frames, errors.New("control attempt ID mismatch")
		}
		switch f.Type {
		case "exposure":
			if len(frames) != 0 || !f.Exposed || f.Time == "" || f.Status != "" || f.Message != "" {
				return frames, errors.New("invalid or duplicate exposure frame")
			}
			if _, err := time.Parse(time.RFC3339Nano, f.Time); err != nil {
				return frames, errors.New("exposure time is not RFC3339")
			}
		case "terminal":
			if f.Time != "" || len(frames) > 1 || (len(frames) == 1 && frames[0].Type != "exposure") || f.Exposed != (len(frames) == 1) || !validTerminalStatus(manifest.Status(f.Status), f.Exposed) {
				return frames, errors.New("invalid terminal frame")
			}
		default:
			return frames, errors.New("invalid control frame type")
		}
		frames = append(frames, f)
	}
	if err := scanner.Err(); err != nil {
		return frames, err
	}
	if len(frames) == 0 || frames[len(frames)-1].Type != "terminal" {
		return frames, errors.New("control protocol requires one terminal frame last")
	}
	return frames, nil
}

func validTerminalStatus(status manifest.Status, exposed bool) bool {
	if !exposed {
		return status == manifest.StatusEnvironmentFailure
	}
	switch status {
	case manifest.StatusCompleted, manifest.StatusAgentTimeout, manifest.StatusBudgetExhausted,
		manifest.StatusAgentProtocolFailure, manifest.StatusEnvironmentFailure, manifest.StatusMCPFailure,
		manifest.StatusProviderFailure, manifest.StatusEvaluatorFailure:
		return true
	default:
		return false
	}
}
