const (
	maxControlBytes  = 64 << 10
	maxControlFrames = 2
	cleanupTimeout   = 15 * time.Second
	runLabelKey      = "io.stacklok.matlatl.eval-run"
)

// ContainerOwnership is the complete identity required to safely clean up one run.
type ContainerOwnership struct {
	CIDFile         string `json:"cidfile"`
	Name            string `json:"name"`
	LabelValue      string `json:"runLabel"`
	ImageID         string `json:"imageId"`
	WorkspaceVolume string `json:"workspaceVolume"`
	TempVolume      string `json:"tempVolume"`
}

// OCIRuntime is the narrow host seam used by ordinary tests.
type OCIRuntime interface {
	Name() string
	InspectImage(context.Context, string) (string, error)
	EnsureContainerAbsent(context.Context, ContainerOwnership) error
	PrepareWorkspace(context.Context, ContainerOwnership) error
	Run(context.Context, []string) ([]byte, error)
	Cleanup(context.Context, ContainerOwnership) error
}

type commandRuntime struct{ name, executable string }

func (r *commandRuntime) Name() string { return r.name }
func (r *commandRuntime) InspectImage(ctx context.Context, image string) (string, error) {
	// executable is resolved from the docker/podman allowlist by SelectRuntime,
	// and image is subsequently required to resolve to an immutable SHA-256 ID.
	out, err := exec.CommandContext(ctx, r.executable, "image", "inspect", "--format", "{{.Id}}", image).CombinedOutput() //nolint:gosec // Runtime executable is allowlisted.
	if err != nil {
		return "", fmt.Errorf("%s image inspect: %w: %s", r.name, err, boundedMessage(string(out)))
	}
	id := strings.TrimSpace(string(out))
	if len(id) == 64 {
		id = "sha256:" + id // Podman formats .Id without Docker's algorithm prefix.
	}
	if !validImageID(id) {
		return "", fmt.Errorf("%s returned non-immutable image ID %q", r.name, id)
	}
	return id, nil
}
func (r *commandRuntime) Run(ctx context.Context, args []string) ([]byte, error) {
	childCtx, cancel := context.WithCancel(ctx)
	defer cancel()
	// r.executable is resolved from the docker/podman allowlist; every caller
	// constructs args from validated IDs and fixed OCI flags.
	cmd := exec.CommandContext(childCtx, r.executable, args...) //nolint:gosec // Runtime and argv vocabulary are constrained by this package.
	stdout := limitedBuffer{limit: maxControlBytes, overflow: cancel}
	stderr := limitedBuffer{limit: maxControlBytes, overflow: cancel}
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	err := cmd.Run()
	if stdout.Exceeded() || stderr.Exceeded() {
		return stdout.CopyBytes(), errors.New("OCI output exceeded limit; container was killed")
	}
	if err != nil && stderr.Len() != 0 {
		err = fmt.Errorf("%w: %s", err, boundedMessage(string(stderr.CopyBytes())))
	}
	return stdout.CopyBytes(), err
}

func (r *commandRuntime) EnsureContainerAbsent(ctx context.Context, owner ContainerOwnership) error {
	_, err := r.inspectOwnedContainer(ctx, owner.Name)
	if err == nil {
		return fmt.Errorf("%s container name %q already exists", r.name, owner.Name)
	}
	if isContainerAbsent(err) {
		return nil
	}
	return fmt.Errorf("verify fresh container name %q: %w", owner.Name, err)
}

func (r *commandRuntime) PrepareWorkspace(ctx context.Context, owner ContainerOwnership) error {
	volumes := []struct {
		name string
		args []string
	}{
		{owner.WorkspaceVolume, workspaceVolumeCreateArgs(owner.WorkspaceVolume, owner.LabelValue)},
		{owner.TempVolume, tempVolumeCreateArgs(owner.TempVolume, owner.LabelValue)},
	}
	for _, volume := range volumes {
		// Both runtime executable and volume name are selected or generated by this package.
		out, err := exec.CommandContext(ctx, r.executable, "volume", "inspect", volume.name).CombinedOutput() //nolint:gosec // Fixed command and validated generated volume name.
		if err == nil {
			return fmt.Errorf("bounded tmpfs volume %q already exists", volume.name)
		}
		if !isContainerAbsent(fmt.Errorf("%w: %s", err, out)) {
			return fmt.Errorf("verify bounded tmpfs volume absent: %w: %s", err, boundedMessage(string(out)))
		}
	}
	for i, volume := range volumes {
		// volume.args contains only fixed flags and package-generated names/labels.
		out, err := exec.CommandContext(ctx, r.executable, volume.args...).CombinedOutput() //nolint:gosec // Runtime and volume argv are constrained by this package.
		if err != nil {
			var cleanupErr error
			for _, created := range volumes[:i] {
				cleanupErr = errors.Join(cleanupErr, r.cleanupVolume(ctx, owner, created.name))
			}
			return errors.Join(fmt.Errorf("create bounded tmpfs volume: %w: %s", err, boundedMessage(string(out))), cleanupErr)
		}
	}
	return nil
}

func workspaceVolumeCreateArgs(name, label string) []string {
	return tmpfsVolumeCreateArgs(name, label, "size=16m,nr_inodes=2048,mode=0755,uid=65532,gid=65532")
}

func tempVolumeCreateArgs(name, label string) []string {
	return tmpfsVolumeCreateArgs(name, label, "size=16m,nr_inodes=2048,mode=1777,uid=0,gid=0,noexec,nosuid,nodev")
}

func tmpfsVolumeCreateArgs(name, label, options string) []string {
	return []string{"volume", "create", "--driver", "local", "--label", runLabelKey + "=" + label, "--opt", "type=tmpfs", "--opt", "device=tmpfs", "--opt", "o=" + options, name}
}

func (r *commandRuntime) cleanupVolume(ctx context.Context, owner ContainerOwnership, name string) error {
	format := `{{index .Labels "` + runLabelKey + `"}}`
	// name is nonce-generated by this package, and executable is allowlisted.
	out, err := exec.CommandContext(ctx, r.executable, "volume", "inspect", "--format", format, name).CombinedOutput() //nolint:gosec // Fixed command with generated volume name.
	if err != nil {
		if isContainerAbsent(fmt.Errorf("%w: %s", err, out)) {
			return nil
		}
		return fmt.Errorf("inspect bounded tmpfs volume %q: %w: %s", name, err, boundedMessage(string(out)))
	}
	if strings.TrimSpace(string(out)) != owner.LabelValue {
		return fmt.Errorf("bounded tmpfs volume %q ownership mismatch; refusing removal", name)
	}
	out, err = exec.CommandContext(ctx, r.executable, "volume", "rm", "--force", name).CombinedOutput() //nolint:gosec // Runtime is allowlisted and name is package-generated.
	if err != nil {
		return fmt.Errorf("remove bounded tmpfs volume %q: %w: %s", name, err, boundedMessage(string(out)))
	}
	return nil
}

func (r *commandRuntime) cleanupVolumes(ctx context.Context, owner ContainerOwnership) error {
	return errors.Join(r.cleanupVolume(ctx, owner, owner.WorkspaceVolume), r.cleanupVolume(ctx, owner, owner.TempVolume))
}

func (r *commandRuntime) Cleanup(ctx context.Context, owner ContainerOwnership) error {
	var target string
	root, rootErr := evalfs.Root(filepath.Dir(owner.CIDFile))
	if rootErr == nil {
		if content, readErr := evalfs.Read(root, filepath.Base(owner.CIDFile)); readErr == nil {
			if id := strings.TrimSpace(string(content)); validContainerID(id) {
				target = id
			}
		}
	}
	if target == "" {
		identity, err := r.inspectOwnedContainer(ctx, owner.Name)
		if isContainerAbsent(err) {
			return r.cleanupVolumes(ctx, owner)
		}
		if err != nil {
			return fmt.Errorf("inspect cleanup fallback %q: %w", owner.Name, err)
		}
		if identity.Label != owner.LabelValue || identity.ImageID != owner.ImageID {
			return fmt.Errorf("container %q ownership mismatch; refusing removal", owner.Name)
		}
		target = identity.ID
	}
	// target is either a verified cidfile value or a verified inspected container ID.
	out, removeErr := exec.CommandContext(ctx, r.executable, "rm", "--force", "--volumes", target).CombinedOutput() //nolint:gosec // Allowlisted runtime and validated container ID.
	if removeErr != nil {
		return fmt.Errorf("%s remove container %s: %w: %s", r.name, target, removeErr, boundedMessage(string(out)))
	}
	_, inspectErr := r.inspectOwnedContainer(ctx, owner.Name)
	if inspectErr == nil {
		return fmt.Errorf("%s container %q remains after forced removal", r.name, owner.Name)
	}
	if ctx.Err() != nil {
		return ctx.Err()
	}
	if !isContainerAbsent(inspectErr) {
		return fmt.Errorf("%s could not verify container %q absent: %w", r.name, owner.Name, inspectErr)
	}
	return r.cleanupVolumes(ctx, owner)
}

type containerIdentity struct{ ID, ImageID, Label string }

func (r *commandRuntime) inspectOwnedContainer(ctx context.Context, name string) (containerIdentity, error) {
	format := `{{.Id}}|{{.Image}}|{{index .Config.Labels "` + runLabelKey + `"}}`
	// name is generated by uniqueContainerName or validated ownership state.
	out, err := exec.CommandContext(ctx, r.executable, "container", "inspect", "--format", format, name).CombinedOutput() //nolint:gosec // Allowlisted runtime and package-generated name.
	if err != nil {
		return containerIdentity{}, fmt.Errorf("%w: %s", err, boundedMessage(string(out)))
	}
	parts := strings.Split(strings.TrimSpace(string(out)), "|")
	if len(parts) == 3 && len(parts[1]) == 64 {
		parts[1] = "sha256:" + parts[1]
	}
	if len(parts) != 3 || !validContainerID(parts[0]) || !validImageID(parts[1]) {
		return containerIdentity{}, errors.New("runtime returned malformed container identity")
	}
	return containerIdentity{ID: parts[0], ImageID: parts[1], Label: parts[2]}, nil
}

func isContainerAbsent(err error) bool {
	if err == nil {
		return false
	}
	message := strings.ToLower(err.Error())
	return strings.Contains(message, "no such") || strings.Contains(message, "no container") || strings.Contains(message, "does not exist") || strings.Contains(message, "not found")
}

func validContainerID(id string) bool {
	if len(id) < 12 || len(id) > 64 {
		return false
	}
	_, err := hex.DecodeString(id)
	return err == nil
}

// SelectRuntime accepts only auto, docker, or podman. Auto deliberately prefers Podman.
func SelectRuntime(choice string) (OCIRuntime, error) {
	if choice == "" {
		choice = "auto"
	}
	if choice != "auto" && choice != "docker" && choice != "podman" {
		return nil, fmt.Errorf("unsupported OCI runtime %q", choice)
	}
	candidates := []string{choice}
	if choice == "auto" {
		candidates = []string{"podman", "docker"}
	}
	for _, name := range candidates {
		path, err := exec.LookPath(name)
		if err == nil {
			return &commandRuntime{name: name, executable: path}, nil
		}
	}
	return nil, fmt.Errorf("OCI runtime %q unavailable (require Docker or Podman)", choice)
}

func validImageID(value string) bool {
	if !strings.HasPrefix(value, "sha256:") || len(value) != 71 {
		return false
	}
	_, err := hex.DecodeString(strings.TrimPrefix(value, "sha256:"))
	return err == nil
}

// BuildImage creates an offline scratch image from a fresh context containing only
// the Containerfile and two statically linked binaries. It returns the runtime,
// immutable image ID, and generated tag; callers own removal of the returned tag.
func BuildImage(ctx context.Context, choice, repositoryRoot string) (runtimeName, imageID, tag string, retErr error) {
	r, err := SelectRuntime(choice)
	if err != nil {
		return "", "", "", err
	}
	cr, ok := r.(*commandRuntime)
	if !ok {
		return "", "", "", errors.New("image building requires a command runtime")
	}
	contextDir, err := buildContext(ctx, repositoryRoot)
	if err != nil {
		return "", "", "", err
	}
	defer func() { retErr = errors.Join(retErr, os.RemoveAll(contextDir)) }()
	tagBytes := sha256.Sum256([]byte(time.Now().UTC().Format(time.RFC3339Nano) + repositoryRoot))
	tagSuffix := hex.EncodeToString(tagBytes[:8])
	tag = "matlatl-eval-fake:" + tagSuffix
	imageRunID := os.Getenv("MATLATL_SCHEDULED_RUN_ID")
	if !validRunID(imageRunID) {
		imageRunID = "build-" + tagSuffix
	}
	args := imageBuildArgs(r.Name(), dockerBuildxAvailable(ctx, cr), contextDir, tag, imageRunID)
	// cr.executable is allowlisted; imageBuildArgs uses fixed flags, a generated tag,
	// and paths beneath the harness-created context directory.
	out, buildErr := exec.CommandContext(ctx, cr.executable, args...).CombinedOutput() //nolint:gosec // Runtime and complete build argv are constrained above.
	if buildErr != nil {
		return "", "", "", fmt.Errorf("%s build: %w: %s", r.Name(), buildErr, boundedMessage(string(out)))
	}
	id, err := r.InspectImage(ctx, tag)
	if err != nil {
		cleanupCtx, cleanupCancel := context.WithTimeout(context.Background(), cleanupTimeout)
		cleanupOut, cleanupErr := exec.CommandContext(cleanupCtx, cr.executable, "image", "rm", "--force", tag).CombinedOutput() //nolint:gosec // Allowlisted runtime and harness-generated tag.
		cleanupCancel()
		if cleanupErr != nil && !strings.Contains(strings.ToLower(string(cleanupOut)), "no such") {
			return "", "", tag, errors.Join(err, fmt.Errorf("cleanup failed build tag: %w: %s", cleanupErr, boundedMessage(string(cleanupOut))))
		}
		return "", "", tag, err
	}
	return r.Name(), id, tag, nil
}

func dockerBuildxAvailable(ctx context.Context, runtime *commandRuntime) bool {
	if runtime.name != "docker" {
		return false
	}
	return exec.CommandContext(ctx, runtime.executable, "buildx", "version").Run() == nil //nolint:gosec // Runtime is the allowlisted Docker executable and argv is fixed.
}

func imageBuildArgs(runtimeName string, buildx bool, contextDir, tag, runID string) []string {
	args := make([]string, 0, 9)
	args = append(args, "build")
	if runtimeName == "docker" && buildx {
		args = []string{"buildx", "build", "--load"}
	}
	return append(args, "--network=none", "--label", runLabelKey+"="+runID, "--file", filepath.Join(contextDir, "Containerfile"), "--tag", tag, contextDir)
}

func buildContext(ctx context.Context, repositoryRoot string) (string, error) {
	contextDir, err := os.MkdirTemp("", "matlatl-eval-image-*")
	if err != nil {
		return "", err
	}
	ok := false
	defer func() {
		if !ok {
			_ = os.RemoveAll(contextDir)
		}
	}()
	for _, item := range []struct{ output, pkg string }{{"supervisor", "./eval/cmd/eval-supervisor"}, {"fake-opencode", "./eval/cmd/fake-opencode"}} {
		cmd := exec.CommandContext(ctx, "go", "build", "-mod=readonly", "-trimpath", "-ldflags=-s -w", "-o", filepath.Join(contextDir, item.output), item.pkg) //nolint:gosec // Fixed Go executable and two-entry package/output allowlist.
		cmd.Dir = repositoryRoot
		cmd.Env = append(os.Environ(), "CGO_ENABLED=0", "GOOS=linux", "GOTOOLCHAIN=local", "GOPROXY=off")
		if data, buildErr := cmd.CombinedOutput(); buildErr != nil {
			return "", fmt.Errorf("build %s: %w: %s", item.output, buildErr, boundedMessage(string(data)))
		}
	}
	containerfile := "FROM scratch\nCOPY supervisor /supervisor\nCOPY fake-opencode /fake-opencode\nENTRYPOINT [\"/supervisor\"]\n"
	if err := os.WriteFile(filepath.Join(contextDir, "Containerfile"), []byte(containerfile), 0o600); err != nil {
		return "", err
	}
	ok = true
	return contextDir, nil
}

func validGeneratedImageTag(tag string) bool {
	const prefix = "matlatl-eval-fake:"
	suffix := strings.TrimPrefix(tag, prefix)
	if suffix == tag || len(suffix) != 16 {
		return false
	}
	_, err := hex.DecodeString(suffix)
	return err == nil
}

// RemoveImage removes the generated tag and the image it references.
func RemoveImage(ctx context.Context, runtimeName, tag string) error {
	if !validGeneratedImageTag(tag) {
		return fmt.Errorf("refusing unexpected generated image tag %q", tag)
	}
	r, err := SelectRuntime(runtimeName)
	if err != nil {
		return err
	}
	cr := r.(*commandRuntime)
	out, err := exec.CommandContext(ctx, cr.executable, "image", "rm", "--force", tag).CombinedOutput() //nolint:gosec // Runtime allowlist and exact generated-tag validation above.
	if err != nil {
		return fmt.Errorf("%s image cleanup: %w: %s", runtimeName, err, boundedMessage(string(out)))
	}
	return nil
}

